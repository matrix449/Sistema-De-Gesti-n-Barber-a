    // --- NUEVO MÉTODO PARA LLENAR LOS RECUADROS ---
    private void cargarDatosCliente(int id) {
        Dao.ClienteDAO dao = new Dao.ClienteDAO();
        Object[] datos = dao.obtenerPorId(id); // Recibimos el arreglo con [Cliente, Usuario]
        
        if (datos != null && datos[0] != null && datos[1] != null) {
            Entity.Cliente cliente = (Entity.Cliente) datos[0];
            Entity.Usuario usuario = (Entity.Usuario) datos[1];
            
            this.idUsuarioRelacionado = cliente.getIdUsuario(); // Guardamos el ID del usuario para luego
            
            // Llenamos los recuadros mezclando los datos
            NombreClieRell1.setText(usuario.getNombre());
            ApellidoClieRell1.setText(usuario.getApellido());
            TelefonoClieRell1.setText(usuario.getTelefono());
            EmailClieRell1.setText(usuario.getEmail());
            ContraseñaRell1.setText(usuario.getPassword());
            FechaNacClieRell1.setText(cliente.getFecha_de_nacimiento());
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar los datos del cliente.");
        }
    }
    
