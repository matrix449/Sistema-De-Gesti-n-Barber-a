    private void BotonModificarClienActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotonModificarClienActionPerformed
    // 1. Obtener textos
        String nombre = NombreClieRell1.getText();
        String apellido = ApellidoClieRell1.getText();
        String telefono = TelefonoClieRell1.getText();
        String email = EmailClieRell1.getText();
        String fechaNac = FechaNacClieRell1.getText();
        String password = ContraseñaRell1.getText();

        if (nombre.isEmpty() || apellido.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, complete al menos Nombre, Apellido y Contraseña.");
            return;
        }

        // 2. Objeto Usuario (con los datos a actualizar)
        Entity.Usuario u = new Entity.Usuario();
        u.setNombre(nombre);
        u.setApellido(apellido);
        u.setTelefono(telefono);
        u.setEmail(email);
        u.setPassword(password);

        // 3. Objeto Cliente (con la fecha y los IDs)
        Entity.Cliente c = new Entity.Cliente();
        c.setFecha_de_nacimiento(fechaNac);
        c.setIdCliente(this.idClienteSeleccionado);
        c.setIdUsuario(this.idUsuarioRelacionado);

        // 4. Llamar al DAO (Transacción)
        Dao.ClienteDAO dao = new Dao.ClienteDAO();
        if (dao.modificarCompleto(u, c)) {
            javax.swing.JOptionPane.showMessageDialog(this, "¡Cliente modificado exitosamente!");
            CientesDash dash = new CientesDash();
            dash.setVisible(true);
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al modificar en la base de datos.");
        }
    }//GEN-LAST:event_BotonModificarClienActionPerformed

